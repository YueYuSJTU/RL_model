"""Build the LaTeX tables that replace the reward-dependent evaluation metrics.

Metrics of the evaluation table (reward-independent, measured by
scripts/ablation/measure_capability_profile.py in the same engagements as the
benchmark evaluation):

  dEs               mean specific-energy margin over the opponent
  turn_rate_mean    aerodynamic turn rate omega = g*sqrt(n^2-1)/V
  react_r2          squared correlation between the line-of-sight angle and the
                    signed turn rate
  corner_adherence  exp(-lambda*|V-Vc|/Vc) over the manoeuvring steps

None of them occurs in any term of the reward function of the evaluated policy
(shape = stage2 / stage1, task_tracking.py:382-438, plus the terminal override
at task_tracking.py:1000-1015).

Output: configs/ablation/tables_eval_metrics.tex

Usage:
  python scripts/ablation/make_paper_tables_eval.py                    # paper table
  python scripts/ablation/make_paper_tables_eval.py --only ablation     # ablation table
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)
OUT = os.path.join("configs", "ablation", "tables_eval_metrics.tex")

# order of the models in the paper's tables
PAPER_ORDER = ["Baseline", "BC", "BD", "BDC-MLP", "BDC-LSTM"]
# ablation arms: label in the paper -> label in the capability run
ABLATION_ARMS = [("With initialization", "Init-with"),
                 ("Without initialization", "Init-without")]

KEYS = ["dEs", "react_r2_phys"]
# the ablation table reports the metric that separates the two arms most clearly
ABL_KEYS = ["react_r2_phys"]
COLS = {                       # key -> (title, format)
    "dEs": (r"$\Delta E_s$ (ft)", "%+.0f"),
    "turn_rate_mean": (r"Turn rate (deg/s)", "%.2f"),
    "react_r2_phys": (r"LOS $R^2$", "%.2f"),
    "corner_adherence": (r"Corner-speed adherence", "%.3f"),
}


def capability(group):
    path = os.path.join("experiments", "capability_profile", group, "merged.json")
    if not os.path.exists(path):
        return {}
    recs = [r for r in json.load(open(path)) if r.get("ok")]
    out = {}
    for m in {r["model"] for r in recs}:
        rs = [r for r in recs if r["model"] == m]
        vals = {}
        for k in KEYS:
            v = [(r["metrics"][k], r["n_episodes"]) for r in rs
                 if r["metrics"].get(k) is not None]
            vals[k] = sum(a * b for a, b in v) / sum(b for _a, b in v) if v else None
        vals["pair_win_rate"] = sum(r["metrics"]["win_rate"] * r["n_episodes"] for r in rs) \
            / sum(r["n_episodes"] for r in rs)
        vals["n_pairs"] = len(rs)
        vals["episodes_per_pair"] = rs[0]["n_episodes"]
        out[m] = vals
    return out


def headline(rows, fmt="%s"):
    return " & ".join(fmt % v for v in rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", choices=["paper", "ablation", "both"], default="both")
    args = ap.parse_args()

    cap = capability("paper")
    abl = capability("ablation")
    if not cap:
        raise SystemExit("no capability profile: run measure_capability_profile.py --group paper")

    eps = next(iter(cap.values()))["episodes_per_pair"]
    L = ["% generated by scripts/ablation/make_paper_tables_eval.py -- do not edit by hand", ""]

    if args.only in ("paper", "both"):
        L += [
            r"\begin{table}[h]",
            r"\caption{Capability metrics of the five compared models, measured with the protocol of "
            r"Section~\ref{sec:eval_benchmark} ($8\times%d$ engagements per model with randomised "
            r"initial states). $\Delta E_s$ is the mean specific-energy margin over the opponent; the "
            r"turn rate is the aerodynamic turn rate of a coordinated turn, $\omega=g\sqrt{n^{2}-1}/V$, "
            r"with the load factor $n$ read from the simulator; the line-of-sight figure $R^{2}$ is the "
            r"squared correlation between the line-of-sight angle to the opponent and the signed turn "
            r"rate, the sign being taken from the bank angle so that the heading changes produced by "
            r"rolling do not contaminate the estimator; and the corner-speed adherence is $\exp(-\lambda\lvert V-V_c\rvert/V_c)$ with "
            r"$\lambda=5$, averaged over the manoeuvring steps of the engagement, where $V_c$ is the "
            r"corner speed evaluated at the instantaneous altitude and weight. None of these quantities "
            r"appears in any term of the reward functions of Section~\ref{sec:reward_curriculum}, so the "
            r"comparison is not circular.}" % eps,
            r"\label{tab:reward_free_metrics}",
            r"\small",
            r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}lrrrr}",
            r"\toprule",
            "Model & " + " & ".join(COLS[k][0] for k in KEYS) + r" \\",
            r"\midrule",
        ]
        for name in PAPER_ORDER:
            c = cap.get(name)
            if not c:
                continue
            L.append("%s & %s \\\\" % (name, " & ".join(COLS[k][1] % c[k] for k in KEYS)))
        L += [r"\botrule", r"\end{tabular*}", r"\end{table}", ""]

    if args.only in ("ablation", "both") and abl:
        L += [
            r"\begin{table}[h]",
            r"\caption{Behavioural metrics of the two arms of the opponent-pool initialization "
            r"ablation, measured on the benchmark opponent pool ($8\times%d$ engagements per arm). "
            r"The metrics are defined as in Table~\ref{tab:reward_free_metrics} and, like them, "
            r"occur in no term of the reward function; the gun-opportunity ratio of the previous "
            r"version of this table has been removed for that reason.}" % eps,
            r"\label{tab:init_ablation_metrics}",
            r"\small",
            r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}lrrrr}",
            r"\toprule",
            r"Arm & " + " & ".join(COLS[k][0] for k in ABL_KEYS) + r" \\",
            r"\midrule",
        ]
        for label, key in ABLATION_ARMS:
            c = abl.get(key)
            if not c:
                continue
            L.append("%s & %s \\\\" % (label, " & ".join(COLS[k][1] % c[k] for k in ABL_KEYS)))
        L += [r"\botrule", r"\end{tabular*}", r"\end{table}", ""]

    with open(OUT, "w") as fh:
        fh.write("\n".join(L))
    print("\n".join(L))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
